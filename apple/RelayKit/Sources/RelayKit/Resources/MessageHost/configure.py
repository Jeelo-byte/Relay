"""Runs inside the pinned Synapse image. Secrets never go to stdout."""
import json
import os
from pathlib import Path
import secrets
import sys
import yaml

PRIVATE = Path('/private')
PORTS = {'whatsapp': 29318, 'discord': 29334, 'gmessages': 29336, 'instagram': 29320}

def save(path, value):
    temporary = path.with_suffix('.tmp')
    temporary.write_text(yaml.safe_dump(value, sort_keys=False))
    temporary.chmod(0o600)
    owner = path.stat() if path.exists() else path.parent.stat()
    os.chown(temporary, owner.st_uid, owner.st_gid)
    temporary.replace(path)

def homeserver():
    path = PRIVATE / 'synapse/homeserver.yaml'
    config = yaml.safe_load(path.read_text())
    if config['server_name'] != 'relay.local':
        raise RuntimeError('This host belongs to another Matrix server. Select a fresh Relay host directory.')
    config.update(enable_registration=False, report_stats=False, trusted_key_servers=[])
    config.setdefault('registration_shared_secret', secrets.token_urlsafe(48))
    config['listeners'] = [{'port': 8008, 'tls': False, 'type': 'http',
        'bind_addresses': ['0.0.0.0'], 'resources': [{'names': ['client'], 'compress': False}]}]
    # Container-local paths generated by Synapse must use its /data mount.
    save(path, config)
    element = PRIVATE / 'element/config.json'
    element.write_text(json.dumps({'default_server_config': {'m.homeserver': {
        'base_url': 'http://localhost:' + os.environ.get('RELAY_MATRIX_PORT', '8008'), 'server_name': 'relay.local'}},
        'disable_custom_urls': True, 'disable_guests': True}))

def bridge(name):
    path = PRIVATE / name / 'config.yaml'
    if not path.exists():
        raise RuntimeError(f'{name}: Docker did not generate a configuration. Check image download and retry.')
    config = yaml.safe_load(path.read_text())
    config['homeserver'].update(address='http://synapse:8008', domain='relay.local')
    app = config['appservice']
    app.update(address=f'http://{name}:{PORTS[name]}', hostname='0.0.0.0', port=PORTS[name])
    for key in ['as_token', 'hs_token']:
        if not app.get(key) or app[key] == 'generate' or 'generated' in app[key]:
            app[key] = secrets.token_urlsafe(48)
    # Keep an existing database configuration intact on retries/upgrades.
    database = config.get('database', app.get('database'))
    if not (PRIVATE / name / 'registration.yaml').exists():
        database.update(type='sqlite3-fk-wal', uri='file:/data/bridge.db?_txlock=immediate')
    permissions = config['bridge'].setdefault('permissions', {})
    permissions.pop('*', None)
    permissions['@relay:relay.local'] = 'admin'
    encryption = config.get('encryption', config['bridge'].get('encryption'))
    if encryption is not None:
        encryption.update(allow=False, default=False, require=False)
    config['bridge']['federate_rooms'] = False
    config['logging'] = {'min_level': 'warn', 'writers': [{'type': 'stdout', 'format': 'json'}]}
    # No historical message import during pairing. Relay selects chats explicitly.
    if 'backfill' in config:
        config['backfill']['enabled'] = False
        config['backfill']['max_initial_messages'] = 0
    for key in ['backfill', 'message_history']:
        if isinstance(config['bridge'].get(key), dict):
            config['bridge'][key]['enabled'] = False
    if name == 'instagram':
        config['network']['mode'] = 'instagram'
        app['id'] = 'instagram'
        config['bridge']['username_template'] = 'instagram_{{.}}'
        app.setdefault('bot', {})['username'] = 'instagrambot'
    save(path, config)

def registration(name):
    source = PRIVATE / name / 'registration.yaml'
    if not source.exists():
        raise RuntimeError(f'{name}: registration generation failed. Check bridge configuration.')
    registration = yaml.safe_load(source.read_text())
    save(PRIVATE / 'synapse' / f'{name}-registration.yaml', registration)
    path = PRIVATE / 'synapse/homeserver.yaml'
    config = yaml.safe_load(path.read_text())
    registrations = config.setdefault('app_service_config_files', [])
    entry = f'/data/{name}-registration.yaml'
    if entry not in registrations:
        registrations.append(entry)
    save(path, config)

if __name__ == '__main__':
    os.umask(0o077)
    {'homeserver': homeserver, 'bridge': bridge, 'registration': registration}[sys.argv[1]](*sys.argv[2:])
